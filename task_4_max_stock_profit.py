"""
Задача 4. Максимальная прибыль от продажи акций (не более k сделок).

Теоретическая оценка сложности:
- Временная сложность:
  * Если k >= n // 2 (число разрешенных сделок не ограничивает стратегию): O(n).
  * В общем случае: O(n * k), где n — количество дней, k — максимальное число сделок.
- Затраты по памяти: O(k), так как мы храним только два массива длиной k + 1 (buy и sell)
  для текущего состояния динамического программирования.
"""

from typing import List


def max_profit(k: int, prices: List[int]) -> int:
    """
    Находит максимальную прибыль при совершении не более k сделок.
    Покупка и продажа в один день запрещены.
    """
    n = len(prices)
    if n < 2 or k <= 0:
        return 0

    # Оптимизация: за n дней невозможно совершить более n // 2 прибыльных непересекающихся сделок.
    # Если k >= n // 2, задача сводится к сбору всех положительных перепадов цен.
    if k >= n // 2:
        profit = 0
        for i in range(1, n):
            if prices[i] > prices[i - 1]:
                profit += prices[i] - prices[i - 1]
        return profit

    # buy[j]  — макс. прибыль после покупки акции в рамках j-й сделки
    # sell[j] — макс. прибыль после продажи акции в рамках j-й сделки
    buy = [-float('inf')] * (k + 1)
    sell = [0] * (k + 1)

    for price in prices:
        # Идем по сделкам от 1 до k. Использование значений с предыдущего дня (или обновление
        # в правильном порядке) гарантирует отсутствие покупки и продажи в один и тот же день.
        for j in range(k, 0, -1):
            sell[j] = max(sell[j], buy[j] + price)
            buy[j] = max(buy[j], sell[j - 1] - price)

    return sell[k]


if __name__ == "__main__":
    # Пример из условия: prices = [3, 2, 6, 5, 0, 3], k = 2 -> 7
    prices_example = [3, 2, 6, 5, 0, 3]
    k_example = 2
    print(f"Цены: {prices_example}, k = {k_example}")
    print("Максимальная прибыль:", max_profit(k_example, prices_example))
